"""Generate the NPU feasibility budget. All values are USD planning allowances.

This is a cash allocation, not a sales forecast or a supplier quotation.
Only one new compute-chip fabrication is in the base scope. An existing or
shared microcomb and shared test facilities are prerequisites.
"""

import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parent
ASK = 750_000
MONTHS = 15
RESERVE = 100_000
CATEGORIES = [
    ("people", "People / specialist support", 280_000),
    ("fabrication", "Compute-chip fabrication", 120_000),
    ("packaging", "Packaging / assembly", 70_000),
    ("electronics_lab", "Electronics / shared lab", 100_000),
    ("source", "Microcomb / pump / optics access", 50_000),
    ("operations", "Operations / IP", 30_000),
]

SCHEDULE = {
    "people": [18_000] * 10 + [20_000] * 5,
    "fabrication": {5: 30_000, 6: 60_000, 9: 30_000},
    "packaging": {7: 15_000, 8: 25_000, 10: 20_000, 12: 10_000},
    "electronics_lab": [
        2_000, 3_000, 5_000, 5_000, 5_000,
        10_000, 10_000, 10_000, 10_000, 10_000,
        8_000, 7_000, 5_000, 5_000, 5_000,
    ],
    "source": {3: 15_000, 6: 20_000, 11: 15_000},
    "operations": [2_000] * MONTHS,
}


def write_csv(name, rows):
    with (ROOT / name).open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def generate():
    core = sum(amount for _, _, amount in CATEGORIES)
    assert core + RESERVE == ASK
    allocations = [
        {"category": label, "allocation_usd": amount, "status": "Planning allowance; quote or staffing plan required"}
        for _, label, amount in CATEGORIES
    ]
    allocations.append({
        "category": "Contingency reserve",
        "allocation_usd": RESERVE,
        "status": "Held in cash; not scheduled expenditure",
    })
    write_csv("preseed_budget.csv", allocations)

    cash = ASK
    rows = []
    for month in range(1, MONTHS + 1):
        row = {"month": month}
        for key, _, _ in CATEGORIES:
            schedule = SCHEDULE[key]
            row[key + "_usd"] = (
                schedule[month - 1] if isinstance(schedule, list)
                else schedule.get(month, 0)
            )
        row["scheduled_spend_usd"] = sum(row[key + "_usd"] for key, _, _ in CATEGORIES)
        cash -= row["scheduled_spend_usd"]
        row["closing_cash_usd"] = cash
        row["protected_reserve_usd"] = RESERVE
        row["cash_above_reserve_usd"] = cash - RESERVE
        rows.append(row)
    for key, _, amount in CATEGORIES:
        assert sum(row[key + "_usd"] for row in rows) == amount, key
    assert sum(row["scheduled_spend_usd"] for row in rows) == core
    assert all(row["closing_cash_usd"] >= RESERVE for row in rows)
    assert rows[-1]["closing_cash_usd"] == RESERVE
    write_csv("preseed_monthly_budget.csv", rows)

    fabrication_base = dict((key, value) for key, _, value in CATEGORIES)["fabrication"]
    sensitivity = []
    for fabrication in (100_000, fabrication_base, 200_000, 300_000):
        revised_core = core - fabrication_base + fabrication
        total = revised_core + RESERVE
        sensitivity.append({
            "fabrication_only_usd": fabrication,
            "scheduled_core_usd": revised_core,
            "protected_reserve_usd": RESERVE,
            "total_funding_with_reserve_usd": total,
            "working_ask_usd": ASK,
            "additional_funding_to_keep_reserve_usd": max(0, total - ASK),
            "cash_left_from_working_ask_before_contingency_usd": ASK - revised_core,
        })
    write_csv("fabrication_sensitivity.csv", sensitivity)

    # One source of truth for the figures used in both PDFs.
    macros = {
        "FundingAsk": ASK,
        "CoreBudget": core,
        "ReserveBudget": RESERVE,
    }
    values = ["% Generated by preseed_budget.py; amounts in USD."]
    for name, value in macros.items():
        values.append("\\newcommand{\\" + name + "}{\\$" + str(value // 1000) + "k}")
    (ROOT / "budget_values.tex").write_text("\n".join(values) + "\n")
    table = [
        "% Generated by preseed_budget.py.",
        "\\begin{tabular}{lr}",
        "\\toprule",
        "\\textbf{15-month allocation} & \\textbf{USD}\\\\",
        "\\midrule",
    ]
    for _, label, amount in CATEGORIES:
        table.append(label + " & \\$" + str(amount // 1000) + "k\\\\")
    table += [
        "Contingency reserve & \\$" + str(RESERVE // 1000) + "k\\\\",
        "\\midrule",
        "\\textbf{Total} & \\textbf{\\$" + str(ASK // 1000) + "k}\\\\",
        "\\bottomrule",
        "\\end{tabular}",
    ]
    (ROOT / "budget_table.tex").write_text("\n".join(table) + "\n")
    print("15-month core: $" + format(core, ",") + "; reserve: $" +
          format(RESERVE, ",") + "; ask: $" + format(ASK, ",") + ".")
    print("Fabrication sensitivity: " + ", ".join(
        "$" + str(row["fabrication_only_usd"] // 1000) + "k fab -> $" +
        str(row["total_funding_with_reserve_usd"] // 1000) + "k total"
        for row in sensitivity
    ))


if __name__ == "__main__":
    generate()
